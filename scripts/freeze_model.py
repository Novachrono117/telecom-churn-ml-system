def freeze(config) -> tuple[DecisionPolicy, list[IntegrityCheck], str]:
    """Fit, persist and freeze. Returns the policy, its checks and a reload note."""
    threshold_reference = load_threshold_results()
    calibration_reference = load_calibration_results()
    tuning_reference = load_tuning_results()

    # Gates: what is frozen must be what the earlier phases decided.
    frozen = verify_frozen_candidate(tuning_reference)
    calibration_policy = verify_calibration_policy(calibration_reference)
    logger.info("Frozen candidate %s, calibration policy %s", frozen, calibration_policy)

    # From here on, only the training pool exists for this process.
    training = load_training_pool()
    features = build_feature_matrix(training)
    target = np.asarray(encode_target(training[config.target.column]))
    prevalence = positive_prevalence(target)
    logger.info("Training pool: %d rows, positive prevalence %.4f", len(features), prevalence)

    pipeline = fit_final_pipeline(features, target)
    path = dump_pipeline(pipeline)

    # Reload fidelity, on training-pool rows and without reading a single label:
    # this demonstrates serialisation, it does not evaluate anything.
    probe = features.head(RELOAD_PROBE_ROWS)
    before = positive_probability(pipeline, probe)
    reloaded = load_pipeline(path)
    after = positive_probability(reloaded, probe)
    identical = bool(np.array_equal(before, after))
    largest = float(np.max(np.abs(before - after))) if before.size else 0.0
    decisions_before = apply_decision_rule(before, threshold_reference.selection.final_threshold)
    decisions_after = apply_decision_rule(after, threshold_reference.selection.final_threshold)
    same_decisions = bool(np.array_equal(decisions_before, decisions_after))
    fingerprint_match = model_fingerprint(pipeline) == model_fingerprint(reloaded)

    reload_note = (
        f"The pipeline was written, read back, and both objects scored the same "
        f"{probe.shape[0]:,} training-pool rows. The probabilities are "
        f"{'bit-identical' if identical else 'NOT identical'} (largest absolute difference "
        f"{largest:.1e}), the decisions at the frozen threshold are "
        f"{'identical' if same_decisions else 'NOT identical'}, and the model fingerprint of the "
        f"reloaded object {'matches' if fingerprint_match else 'does NOT match'} the one written "
        f"to the policy. **No label was read and no metric was computed**: this demonstrates "
        f"serialisation fidelity, not performance."
    )
    if not (identical and same_decisions and fingerprint_match):
        raise IntegrityError(
            "The reloaded pipeline does not reproduce the in-memory one. "
            f"probabilities identical={identical}, decisions identical={same_decisions}, "
            f"fingerprint match={fingerprint_match}."
        )

    digests = {artefact: file_digest(PROJECT_ROOT / artefact) for artefact in UPSTREAM_ARTEFACTS}
    policy = build_decision_policy(
        pipeline,
        path,
        threshold_reference,
        calibration_reference,
        tuning_reference,
        len(features),
        prevalence,
        digests,
    )
    write_decision_policy(policy)

    # Self-check: the record just written must pass the same verification the
    # --verify command runs, or it is not a freeze anybody can rely on.
    checks, _ = verify_or_raise(load_decision_policy(), threshold_reference, calibration_reference)
    logger.info("Freeze verified: %d integrity checks passed.", len(checks))
    return policy, checks, reload_note


def verify(policy_path: Path | None = None, root: Path | None = None) -> int:
    """Verify an existing freeze. **Strictly read-only.** Returns an exit code.

    This function reads, hashes and compares. It does not fit, dump, write or
    repair, and that is a guarantee rather than a description: a verification
    that regenerated whatever it found missing could never fail, and a check that
    cannot fail is not a check.

    Fail-closed in every direction. A missing pipeline is a failure, not a
    trigger to rebuild it. A divergent fingerprint is a failure, not something to
    correct in place. A divergent provenance digest is a failure, not a reason to
    refresh the policy.

    Args:
        policy_path: Freeze record to verify. Defaults to the real one.
        root: Repository root for resolving the pipeline and the source files.
            Both parameters exist so the fail-closed behaviour can be exercised
            against temporary copies without touching one real artefact.

    Returns:
        ``0`` if every check passed, ``1`` otherwise.
    """
    policy = load_decision_policy(policy_path)
    checks, _ = verify_decision_policy(
        policy, load_threshold_results(), load_calibration_results(), root
    )
    for check in checks:
        logger.log(
            logging.INFO if check.passed else logging.ERROR,
            "%s %s: %s",
            "PASS" if check.passed else "FAIL",
            check.name,
            check.detail,
        )

    failed = [check for check in checks if not check.passed]
    if failed:
        logger.error("%d of %d integrity checks FAILED.", len(failed), len(checks))
        return 1
    logger.info("All %d integrity checks passed.", len(checks))
    logger.info(
        "Frozen policy: %s at threshold %r, calibration %s",
        policy.threshold.threshold_policy,
        policy.threshold.final_threshold,
        policy.calibration.calibration_policy,
    )
    return 0


def main(argv: list[str] | None = None) -> int:
    """Run the freeze, or verify an existing one. Returns a process exit code."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--verify",
        action="store_true",
        help="check the existing freeze and change nothing",
    )
    arguments = parser.parse_args(argv)

    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s: %(message)s")
    config = get_config()

    try:
        verify_split_manifest(load_split_manifest())
        if arguments.verify:
            return verify()
        policy, checks, reload_note = freeze(config)
    except FileNotFoundError as error:
        logger.error("%s", error)
        return 1
    except RawDatasetMismatchError as error:
        logger.error("%s", error)
        return 2
    except SplitManifestMismatchError as error:
        logger.error("%s", error)
        return 3
    except FrozenCandidateMismatchError as error:
        logger.error("%s", error)
        return 4
    except CalibrationPolicyMismatchError as error:
        logger.error("%s", error)
        return 5
    except IntegrityError as error:
        logger.error("%s", error)
        return 6

    Path(REPORT_PATH).write_text(
        build_report(policy, checks, reload_note),
        encoding="utf-8",
        newline="\n",
    )
    logger.info("Wrote %s", REPORT_PATH)
    logger.info("Wrote %s", POLICY_PATH)
    logger.info("Wrote %s", PIPELINE_PATH)
    logger.info(
        "Frozen: %s, calibration %s, threshold %r",
        policy.model.estimator,
        policy.calibration.calibration_policy,
        policy.threshold.final_threshold,
    )
    logger.info("Model fingerprint: %s", policy.artifacts.model_fingerprint_sha256)
    return 0


