def _check_table(checks: list[IntegrityCheck]) -> str:
    lines = ["| Check | Result | Observed |", "| --- | --- | --- |"]
    for check in checks:
        detail = check.detail.replace("|", "\\|")
        verdict = "**PASS**" if check.passed else "**FAIL**"
        lines.append(f"| `{check.name}` | {verdict} | {detail} |")
    return "\n".join(lines)


def _digest_table(policy: DecisionPolicy) -> str:
    digests = policy.provenance["upstream_artefact_digests"]
    lines = ["| Upstream artefact | SHA-256 |", "| --- | --- |"]
    for artefact, digest in digests.items():
        lines.append(f"| `{artefact}` | `{digest[:16]}…` |")
    return "\n".join(lines)


